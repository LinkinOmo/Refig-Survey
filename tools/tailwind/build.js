// Build TailwindCss.html (repo root) — the precompiled stylesheet every page pulls in with
// <?!= includeTailwindCss_() ?> just before </head> (same cascade spot the old CDN <style> landed in).
//
// RUN THIS BEFORE `clasp push` WHENEVER A PAGE GAINS A TAILWIND CLASS NOT USED ANYWHERE BEFORE,
// otherwise that class silently has no style:
//     & "$env:LOCALAPPDATA\node-portable\node-v24.15.0-win-x64\node.exe" tools\tailwind\build.js
// Tailwind CLI is installed outside Google Drive (keeps node_modules from syncing):
//     %LOCALAPPDATA%\tailwind-build   (npm install tailwindcss@3.4.17 there if missing)
// Classes built from variables ('bg-' + color + '-100') must be added to safelist in tailwind.config.js.
const path = require('path');
const fs = require('fs');
const { spawnSync } = require('child_process');

const here = __dirname;
const root = path.resolve(here, '..', '..');
const cli = path.join(process.env.LOCALAPPDATA || '', 'tailwind-build', 'node_modules', 'tailwindcss', 'lib', 'cli.js');
if (!fs.existsSync(cli)) {
  console.error('Tailwind CLI not found at ' + cli + '\nInstall: cd %LOCALAPPDATA%\\tailwind-build && npm install tailwindcss@3.4.17');
  process.exit(1);
}
const tmp = path.join(here, '.out.css');
const r = spawnSync(process.execPath, [cli, '-c', 'tailwind.config.js', '-i', 'input.css', '-o', tmp, '--minify'],
  { cwd: here, stdio: 'inherit' });
if (r.status !== 0) process.exit(r.status || 1);

const css = fs.readFileSync(tmp, 'utf8');
fs.unlinkSync(tmp);
if (css.indexOf('<?') !== -1 || css.indexOf('</style') !== -1) {
  console.error('Generated CSS contains "<?" or "</style" — would break the HtmlService template include.');
  process.exit(1);
}
const out = '<!-- GENERATED by tools/tailwind/build.js — do not edit by hand. Tailwind v3.4.17 -->\n<style>' + css + '</style>\n';
fs.writeFileSync(path.join(root, 'TailwindCss.html'), out);
console.log('TailwindCss.html written: ' + Math.round(out.length / 1024) + ' KB');
