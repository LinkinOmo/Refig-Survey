def clean_file(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        text = f.read()

    original = text
    # Sort keys by length descending to replace longer phrases first!
    for key in sorted(char_map.keys(), key=len, reverse=True):
        text = text.replace(key, char_map[key])

    if text != original:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(text)
        print(f"Fixed string fragments in {filepath}")
        return 1
    return 0

total = 0
for ext in ['*.html', '*.gs']:
    for f in glob.glob(ext):
        total += clean_file(f)

print(f"Total files updated with dictionary replace: {total}")
